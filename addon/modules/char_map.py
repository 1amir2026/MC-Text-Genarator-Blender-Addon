FORMAT_LINE_UNIT = 9
NEWLINE_CHAR = "\\"


def is_known_char(char: str) -> bool:
    return char in CHAR_DATA or char == NEWLINE_CHAR


def char_width(char: str, word_space: float) -> float:
    definition = CHAR_DATA[char]
    if definition.width is None:
        return word_space
    return definition.width
